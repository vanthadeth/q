// Generates assets/mascot/generated.ts from the Muggo SVG sources.
// Originals in assets/mascot/*.svg stay untouched. Colors are kept exactly as supplied.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { optimize } from 'svgo';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'mascot');
const files = readdirSync(root).filter((f) => f.endsWith('.svg')).sort();

const BAD = /<script|<image|data:|href=|<foreignObject|\son[a-z]+=|https?:\/\/(?!www\.w3\.org)/i;

const entries = [];
let before = 0;
let after = 0;
for (const file of files) {
  const source = readFileSync(join(root, file), 'utf8');
  if (BAD.test(source)) throw new Error(`${file} contains unsafe content`);
  const result = optimize(source, {
    multipass: true,
    floatPrecision: 1,
    plugins: [
      { name: 'preset-default', params: { overrides: { removeViewBox: false } } },
      'removeDimensions',
    ],
  });
  const key = file.replace(/^muggo-/, '').replace(/\.svg$/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  before += source.length;
  after += result.data.length;
  entries.push(`  ${key}: ${JSON.stringify(result.data)},`);
}

const out = `// GENERATED by scripts/build-mascot.mjs. Do not edit. Source: assets/mascot/*.svg
export const MUGGO = {
${entries.join('\n')}
} as const;

export type MuggoPose = keyof typeof MUGGO;
`;
writeFileSync(join(root, 'generated.ts'), out);
console.log(`${files.length} poses, ${before} -> ${after} bytes (${Math.round((after / before) * 100)}%)`);
